@app.before_request
def protect_post_requests():
    if request.method == "POST":
        expected_token = session.get("_csrf_token", "")
        submitted_token = request.form.get("csrf_token", "")
        if not expected_token or not submitted_token or not hmac.compare_digest(
            submitted_token.encode("utf-8"), expected_token.encode("utf-8")
        ):
            abort(400)


@app.context_processor
def inject_csrf_token():
    def csrf_token():
        if "_csrf_token" not in session:
            session["_csrf_token"] = secrets.token_hex(32)
        return session["_csrf_token"]

    def image_url(image):
        if image.startswith(("http://", "https://")):
            return image
        return url_for("static", filename=f"uploads/{image}")

    return {"csrf_token": csrf_token, "image_url": image_url}

