@app.route("/add-property", methods=["GET", "POST"])
def add_property():
    if "user_id" not in session:
        flash("Connexion requise pour publier un bien.", "warning")
        return redirect(url_for("login"))

    if request.method == "POST":
        title = request.form["title"].strip()
        property_type = request.form["property_type"]
        offer_type = request.form["offer_type"]
        city = request.form["city"].strip()
        neighborhood = request.form["neighborhood"].strip()
        try:
            price = int(request.form["price"])
            bedrooms = int(request.form.get("bedrooms") or 0)
            bathrooms = int(request.form.get("bathrooms") or 0)
        except ValueError:
            flash("Le prix et le nombre de pièces doivent être des entiers valides.", "danger")
            return redirect(url_for("add_property"))
        if price < 0 or bedrooms < 0 or bathrooms < 0:
            flash("Le prix et le nombre de pièces ne peuvent pas être négatifs.", "danger")
            return redirect(url_for("add_property"))
        description = request.form["description"].strip()

        file = request.files.get("image")
        image_filename = "default_house.jpg"

        if file and file.filename:
            if not allowed_file(file.filename):
                flash("Format d'image non pris en charge. Utilisez PNG, JPG, JPEG ou WebP.", "danger")
                return redirect(url_for("add_property"))

            if CLOUDINARY_CONFIGURED:
                try:
                    upload_result = cloudinary.uploader.upload(
                        file,
                        folder="immo-connect/properties",
                        resource_type="image",
                    )
                except CloudinaryError:
                    current_app.logger.exception("Échec de l'envoi de l'image vers Cloudinary")
                    flash("L'envoi de la photo a échoué. Réessayez dans un instant.", "danger")
                    return redirect(url_for("add_property"))
                image_filename = upload_result["secure_url"]
            else:
                filename = secure_filename(file.filename)
                saved_filename = f"{session['user_id']}_{filename}"
                file.save(os.path.join(app.config['UPLOAD_FOLDER'], saved_filename))
                image_filename = saved_filename

        latitude = request.form.get("latitude")
        longitude = request.form.get("longitude")
        try:
            latitude = float(latitude) if latitude and latitude.strip() else None
            longitude = float(longitude) if longitude and longitude.strip() else None
        except (ValueError, TypeError):
            latitude = None
            longitude = None

        conn = get_db_connection()
        conn.execute('''
            INSERT INTO properties 
            (user_id, title, property_type, offer_type, city, neighborhood, price, bedrooms, bathrooms, description, image, latitude, longitude)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
        ''', (session["user_id"], title, property_type, offer_type, city, neighborhood, price, bedrooms, bathrooms, description, image_filename, latitude, longitude))
        conn.commit()
        conn.close()

        flash("Annonce immobilière publiée !", "success")
        return redirect(url_for("dashboard"))

    return render_template("add_property.html")

