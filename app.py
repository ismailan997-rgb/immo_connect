@app.route("/property/<int:property_id>/review", methods=["POST"])
def add_review(property_id):
    author_name = (request.form.get("author_name") or "").strip()
    rating_value = request.form.get("rating", "")
    comment = (request.form.get("comment") or "").strip()

    if not author_name or not rating_value or not comment:
        flash("Veuillez remplir tous les champs de l'avis.", "danger")
        return redirect(url_for("property_detail", property_id=property_id))

    try:
        rating = int(rating_value)
    except ValueError:
        rating = 0
    if not 1 <= rating <= 5:
        flash("La note doit être comprise entre 1 et 5.", "danger")
        return redirect(url_for("property_detail", property_id=property_id))

    conn = get_db_connection()
    property_exists = conn.execute("SELECT 1 FROM properties WHERE id = %s", (property_id,)).fetchone()
    if property_exists is None:
        conn.close()
        flash("Annonce introuvable.", "danger")
        return redirect(url_for("home"))
    conn.execute(
        "INSERT INTO reviews (property_id, author_name, rating, comment) VALUES (%s, %s, %s, %s)",
        (property_id, author_name, rating, comment)
    )
    conn.commit()
    conn.close()

    flash("Votre avis a bien été publié !", "success")
    return redirect(url_for("property_detail", property_id=property_id))

# 3. Mettre à jour la route property_detail pour récupérer les avis
@app.route("/property/<int:property_id>")
def property_detail(property_id):
    conn = get_db_connection()
    
    property_item = conn.execute("""
        SELECT properties.*, users.phone, users.agency_name, users.email
        FROM properties 
        JOIN users ON properties.user_id = users.id 
        WHERE properties.id = %s
    """, (property_id,)).fetchone()

    # Récupération des avis
    reviews = conn.execute("""
        SELECT * FROM reviews WHERE property_id = %s ORDER BY created_at DESC
    """, (property_id,)).fetchall()
    
    # Calcul de la moyenne des notes
    avg_rating = conn.execute("""
        SELECT AVG(rating) as avg FROM reviews WHERE property_id = %s
    """, (property_id,)).fetchone()["avg"]

    conn.close()

    if property_item is None:
        flash("Annonce introuvable.", "danger")
        return redirect(url_for("home"))

    return render_template("property_detail.html", item=property_item, reviews=reviews, avg_rating=avg_rating)

